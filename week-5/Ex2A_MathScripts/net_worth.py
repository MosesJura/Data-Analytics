# Calculating My Net Worth
# Net worth = total assets − total debts

# 1. Known assets & debts
cash = 5000.00
savings = 12000.00
car_value = 8000.00
investments = 15000.00

credit_card_debt = 2500.00
student_loan = 18000.00
car_loan = 10000.00

# 2. Calculate
total_assets = cash + savings + car_value + investments
total_debts = credit_card_debt + student_loan + car_loan
net_worth = total_assets - total_debts

# 3. Display

print(f'My total assets are {total_assets:,.2f}')
print(f'My total debts are {total_debts:,.2f}')
print(f'My networth is {net_worth:,.2f}')

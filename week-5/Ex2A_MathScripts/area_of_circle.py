# calculate the area of a circle
import math

Diameter = 11 
Radius = Diameter / 2

Area = math.pi * Radius**2

print(f'The diameter of the circle is {Diameter} cm.')
print(f'The radius of the circle is {Radius} cm.')
print(f'The area of the circle is {Area:.2f} cm².')
print(f"The area of a circle with radius {Radius} is {Area:.2f} cm².")